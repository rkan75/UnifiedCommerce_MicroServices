/** Fallback when title is not in map (e.g. "Assorted Produce Item N") – documented working Unsplash example */
const FALLBACK_PRODUCE_IMAGE = unsplash("1458571037713-913d8b481dc6")

/**
 * Returns the image URL for a Produce product by title. Image content matches the product
 * (e.g. apples → apple photo). Uses Unsplash; storefront must allow images.unsplash.com.
 */
export function getProduceImageUrl(title: string): string {
  const normalized = title.replace(/^Organic\s+/i, "").trim()
  return PRODUCE_IMAGES[title] ?? PRODUCE_IMAGES[normalized] ?? FALLBACK_PRODUCE_IMAGE
}

export function isProduceCategory(category: string): boolean {
  return category === "Produce"
}
