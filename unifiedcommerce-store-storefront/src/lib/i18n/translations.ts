export type Locale = keyof typeof translations
export type TranslationKey = keyof typeof translations.en

export const getTranslation = (
  locale: Locale,
  key: string
): string => {
  const keys = key.split(".")
  let value: any = translations[locale]

  for (const k of keys) {
    value = value?.[k]
  }

  return value ?? key
}
